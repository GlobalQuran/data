#!/usr/bin/env python3
"""Rebuilds the "Available data" lists in README.md (Quran texts, translations, transliterations, audio) from the files in this repo.
Run from the repo root:  python3 tools/update_readme_lists.py     (needs PyYAML for the audio files)"""
import re, subprocess, sys, yaml
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CDN = "https://cdn.globalquran.com/quran_data"
AUDIO = "https://audio.globalquran.com"
START, END = "<!-- LISTS:START (generated by tools/update_readme_lists.py, do not edit by hand) -->", "<!-- LISTS:END -->"

tracked = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split("\n")
def folder(name):   # the folder's spelling as git tracks it
    for t in tracked:
        if t.lower().startswith(name.lower() + "/"):
            return t.split("/")[0]
    return name

def header(path):
    kv = {}
    for line in path.read_text(encoding="utf-8").split("\n"):
        m = re.match(r"^#\s*([A-Za-z ]+?)\s*:\s*(.*?)\s*$", line)
        if m:
            kv.setdefault(m.group(1).lower(), m.group(2))
    return kv

def text_table(title, name, blurb):
    d = folder(name)
    rows = []
    for p in sorted((ROOT / d).glob("*.txt")):
        h = header(p)
        if not h.get("id"):
            continue            # no header block: not an edition the sync reads
        i = h["id"]
        status = (h.get("status") or "active").lower()
        note = "" if status == "active" else f" _({status})_"
        rows.append(f"| [`{i}`]({d}/{p.name}) | {h.get('name','')}{note} | {h.get('language','')} | {h.get('translator','')} | "
                    f"[JSON]({CDN}/complete/json/{i}.json) · [first ayah]({CDN}/verse/{i}/1.txt) · [surah 1]({CDN}/surah/{i}/1.txt) |")
    return (f"#### {title} ({len(rows)})\n\n{blurb}\n\n| ID (source file) | Name | Language | Translator / author | Read it (CDN) |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n")

def audio_table():
    rows, n = [], 0
    for p in sorted((ROOT / folder("Audio")).glob("*.yml")):
        a = yaml.safe_load(p.read_text(encoding="utf-8"))
        n += 1
        for v in a.get("variants") or []:
            ext, kbs, mode = v["format"], v["kbs"], v.get("mode", "versebyverse")
            base = v.get("path") or f"{a['id']}/{ext}/{kbs}kbs/"
            base = f"{AUDIO}/{base.strip('/')}/"
            if mode == "surahbysurah":
                links = f"[Al-Fatihah]({base}surah/1.{ext})"
            elif mode == "juzbyjuz":
                links = f"[juz 1]({base}juz/1.{ext})"
            else:
                links = f"[Bismillah (1:1)]({base}1.{ext})" + (f" · [A'udhu]({base}0.{ext})" if v.get("audhubillah") else "")
            st = (v.get("status") or a.get("status") or "").lower()
            rows.append(f"| `{a['id']}` | {a['name']}{(' · ' + a['native_name']) if a.get('native_name') else ''} | {a.get('language','')} | "
                        f"{ext} | {kbs} kbps | {mode} | {st} | {links} |")
    return (f"#### Audio ({n} reciters)\n\nEvery reciter with each format, bit rate and mode it has. Click a link to listen (browsers play mp3 and ogg directly; "
            "GitHub cannot embed an audio player in a README). File names inside a folder follow the structure described under Audio below.\n\n"
            "| ID | Reciter | Language | Format | Bit rate | Mode | Status | Listen |\n|---|---|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n")

block = "\n".join([
    START, "",
    "### Available data",
    "",
    f"Everything here is served from the CDN. Per edition: the whole Quran as one JSON file `{CDN}/complete/json/<id>.json`, "
    f"one verse `{CDN}/verse/<id>/<verse number 1..6236>.txt`, one surah `{CDN}/surah/<id>/<1..114>.txt`, page `…/page/<id>/<1..604>.txt` and juz `…/juz/<id>/<1..30>.txt` "
    "(each also as `.jsonp`). Editions marked _(draft)_ or _(incomplete)_ are not public yet, so their links may not work until they are enabled.",
    "",
    text_table("Quran texts", "Quran", "Arabic text editions."),
    text_table("Translations", "Translation", "Translations and tafsir, by language code."),
    text_table("Transliterations", "Transliteration", "The Arabic text written in another script."),
    audio_table(), END,
])
readme = (ROOT / "README.md").read_text(encoding="utf-8")
if START in readme:
    readme = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, readme, flags=re.S)
else:
    readme = readme.rstrip("\n") + "\n\n" + block + "\n"
(ROOT / "README.md").write_text(readme, encoding="utf-8")
print("README updated")
